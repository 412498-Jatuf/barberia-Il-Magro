-- Esquema inicial de Il Magro

CREATE TABLE corte (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(255) NOT NULL,
    descripcion VARCHAR(500),
    categoria   VARCHAR(255),
    imagen_url  VARCHAR(255) NOT NULL
);

CREATE TABLE servicio (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(255)   NOT NULL,
    descripcion      VARCHAR(255),
    duracion_minutos INTEGER        NOT NULL CHECK (duracion_minutos > 0),
    precio           NUMERIC(10, 2) NOT NULL CHECK (precio >= 0)
);

CREATE TABLE barbero (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(255) NOT NULL,
    especialidad VARCHAR(255),
    foto_url     VARCHAR(255)
);

CREATE TABLE turno (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_nombre   VARCHAR(100) NOT NULL,
    cliente_telefono VARCHAR(20)  NOT NULL,
    cliente_email    VARCHAR(150),
    servicio_id      BIGINT       NOT NULL REFERENCES servicio (id),
    barbero_id       BIGINT       NOT NULL REFERENCES barbero (id),
    fecha            DATE         NOT NULL,
    hora_inicio      TIME         NOT NULL,
    hora_fin         TIME         NOT NULL,
    estado           VARCHAR(20)  NOT NULL CHECK (estado IN ('CONFIRMADO', 'CANCELADO')),
    notas            VARCHAR(500),
    creado_en        TIMESTAMP    NOT NULL
);

CREATE INDEX idx_turno_barbero_fecha ON turno (barbero_id, fecha);
