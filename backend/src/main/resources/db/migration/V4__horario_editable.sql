-- Horario semanal: un renglon por tramo. Un dia con dos tramos tiene pausa; sin tramos, esta cerrado.
CREATE TABLE horario_tramo (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia_semana INTEGER NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
    desde      TIME    NOT NULL,
    hasta      TIME    NOT NULL,
    CHECK (hasta > desde)
);

CREATE INDEX idx_horario_tramo_dia ON horario_tramo (dia_semana);

-- Cierres puntuales: un dia entero (desde y hasta vacios) o unas horas de un dia.
CREATE TABLE bloqueo_agenda (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha  DATE NOT NULL,
    desde  TIME,
    hasta  TIME,
    motivo VARCHAR(200)
);

CREATE INDEX idx_bloqueo_agenda_fecha ON bloqueo_agenda (fecha);

